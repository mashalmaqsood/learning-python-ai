# Lab 2: Working with Types in Python

# Q0: What is the type of 12.0?
print(type(12.0))  # float

# Q1: What is the data type of the result of: 6 / 2?
print(type(6 / 2))  # float

# Q3: What is the type of the result of: "Hello, World!"?
print(type("Hello, World!"))  # str

# Q4: What is the type of the result of: "hello" == "world"?
print(type("hello" == "world"))  # bool

# Q5: Convert employee id "1001" to an integer
print(int("1001"))

# Q6: Convert financial value "1234.56" to a float
print(float("1234.56"))

# Q7: Convert phone number 123-456-7890 to a string
print(str("123-456-7890"))
